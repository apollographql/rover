//! `rover plugin uninstall` through the real binary: which copies it removes
//! at which level, what it does to the declarations, and that it never
//! reaches the registry.

use std::{fs, process::Command};

use assert_cmd::cargo::cargo_bin;
use camino::{Utf8Path, Utf8PathBuf};
use httpmock::MockServer;
use insta::assert_json_snapshot;
use rstest::rstest;
use serde_json::Value;
use speculoos::prelude::*;

use crate::support::plugin_levels::{Level, TwoLevels, two_levels};

const MANIFEST: &str = indoc::indoc! {r#"
    # This project's plugins.
    settings:
      APOLLO_TELEMETRY_DISABLED: true   # in CI too

    plugins:
      # Pinned for the gateway tests.
      router: "=2.1.0"
      supergraph: "2"  # composition
"#};

const LOCKED: &str = "# This file is generated by Rover. It is not intended for manual editing.\n\
                      version = 1\n\n\
                      [[plugins]]\nname = \"supergraph\"\nrequested = \"2\"\nresolved = \"2.9.3\"\n\n\
                      [[plugins]]\nname = \"router\"\nrequested = \"=2.1.0\"\nresolved = \"2.1.0\"\n";

/// [`LOCKED`] once `supergraph` is uninstalled.
const LOCKED_ROUTER_ONLY: &str = "# This file is generated by Rover. It is not intended for manual editing.\n\
                                  version = 1\n\n\
                                  [[plugins]]\nname = \"router\"\nrequested = \"=2.1.0\"\nresolved = \"2.1.0\"\n";

/// What a run of `rover plugin uninstall` printed, with the temporary
/// directories redacted.
struct Uninstalled {
    code: Option<i32>,
    stderr: String,
    json: Option<Value>,
}

/// Run `rover plugin uninstall <args>` at `levels`, with the registry a
/// server that fails the test if anything asks it for anything.
fn uninstall(levels: &TwoLevels, args: &[&str]) -> Uninstalled {
    let server = MockServer::start();
    let registry = server.mock(|when, then| {
        when.any_request();
        then.status(500);
    });
    let mut command = Command::new(cargo_bin("rover"));
    levels.apply(&mut command);
    let output = command
        .args(["plugin", "uninstall"])
        .args(args)
        .args(["--download-host", &format!("http://{}", server.address())])
        .args(["--skip-update-check", "--telemetry-disabled"])
        .env("NO_COLOR", "1")
        // CI sets these, and an error would print its backtrace.
        .env("RUST_BACKTRACE", "0")
        .env("RUST_LIB_BACKTRACE", "0")
        // binstall reads this directly, and it would move the global root.
        .env_remove("APOLLO_NODE_MODULES_BIN_DIR")
        .env_remove("APOLLO_ROVER_GLOBAL")
        .output()
        .unwrap();
    registry.assert_calls(0);

    Uninstalled {
        code: output.status.code(),
        stderr: redact(levels, &String::from_utf8_lossy(&output.stderr)),
        json: serde_json::from_slice(&output.stdout)
            .ok()
            .map(|json| redact_strings(levels, json)),
    }
}

/// `text` with each level's directory named rather than spelled out, `/` as
/// the separator, and no executable suffix.
fn redact(levels: &TwoLevels, text: &str) -> String {
    text.replace(levels.project.root().as_str(), "[project]")
        .replace(levels.global.home().as_str(), "[home]")
        .replace('\\', "/")
        .replace(std::env::consts::EXE_SUFFIX, "")
}

fn redact_strings(levels: &TwoLevels, json: Value) -> Value {
    match json {
        Value::String(text) => Value::String(redact(levels, &text)),
        Value::Array(values) => Value::Array(
            values
                .into_iter()
                .map(|value| redact_strings(levels, value))
                .collect(),
        ),
        Value::Object(fields) => Value::Object(
            fields
                .into_iter()
                .map(|(key, value)| (key, redact_strings(levels, value)))
                .collect(),
        ),
        other => other,
    }
}

/// The releases of `plugin` installed in `bin_dir`, oldest first.
fn installed(bin_dir: &Utf8Path, plugin: &str) -> Vec<String> {
    let prefix = format!("{plugin}-v");
    let mut versions: Vec<String> = fs::read_dir(bin_dir)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .filter_map(|entry| {
                    let name = entry.file_name().to_string_lossy().to_string();
                    let name = name
                        .strip_suffix(std::env::consts::EXE_SUFFIX)
                        .unwrap_or(&name)
                        .to_string();
                    name.strip_prefix(&prefix).map(str::to_string)
                })
                .collect()
        })
        .unwrap_or_default();
    versions.sort();
    versions
}

fn read(path: Utf8PathBuf) -> String {
    fs::read_to_string(path).unwrap()
}

/// A project declaring `router` and `supergraph` in a commented manifest,
/// locked at v2.1.0 and v2.9.3, with `supergraph` v2.9.2 and v2.9.3 and
/// `router` v2.1.0 installed there, and `supergraph` v2.9.3 installed
/// globally too.
fn declared_project(levels: &TwoLevels) {
    fs::write(levels.project.rover_dir().join("rover.yaml"), MANIFEST).unwrap();
    fs::write(
        levels.project.rover_dir().join("plugin-versions.lock"),
        LOCKED,
    )
    .unwrap();
    levels.seed_plugin(Level::Project, "supergraph", "2.9.2");
    levels.seed_plugin(Level::Project, "supergraph", "2.9.3");
    levels.seed_plugin(Level::Project, "router", "2.1.0");
    levels.seed_plugin(Level::Global, "supergraph", "2.9.3");
}

#[rstest]
fn a_bare_name_removes_every_copy_and_the_declarations(two_levels: TwoLevels) {
    declared_project(&two_levels);

    let result = uninstall(&two_levels, &["supergraph", "--format", "json"]);

    assert_that!(result.code).is_equal_to(Some(0));
    assert_that!(result.stderr.as_str()).is_equal_to(
        "Removed `supergraph` v2.9.3 from this project.\n\
         Removed `supergraph` v2.9.2 from this project.\n",
    );
    assert_json_snapshot!(result.json);
    assert_that!(installed(&two_levels.project.bin_dir(), "supergraph")).is_empty();
    // The manifest differs only by the `supergraph` line.
    assert_that!(read(two_levels.project.rover_dir().join("rover.yaml")))
        .is_equal_to(MANIFEST.replace("  supergraph: \"2\"  # composition\n", ""));
    assert_that!(read(
        two_levels.project.rover_dir().join("plugin-versions.lock")
    ))
    .is_equal_to(LOCKED_ROUTER_ONLY.to_string());
    // The other level is untouched.
    assert_that!(installed(&two_levels.global.bin_dir(), "supergraph"))
        .is_equal_to(vec!["2.9.3".to_string()]);
}

#[rstest]
#[case::an_extra_release("supergraph@=2.9.2", vec!["2.9.3"], "")]
#[case::the_locked_release(
    "supergraph@=2.9.3",
    vec!["2.9.2"],
    "warning: `plugin-versions.lock` records `supergraph` v2.9.3, which is no longer installed \
     in this project. The next plugin-using command will download it again, or fail if downloads \
     are disabled.\n"
)]
fn one_release_of_several_keeps_the_declarations(
    two_levels: TwoLevels,
    #[case] named: &str,
    #[case] left: Vec<&str>,
    #[case] warning: &str,
) {
    declared_project(&two_levels);
    let removed = named.split_once("@=").unwrap().1;

    let result = uninstall(&two_levels, &[named]);

    assert_that!(result.code).is_equal_to(Some(0));
    assert_that!(result.stderr).is_equal_to(format!(
        "Removed `supergraph` v{removed} from this project.\n{warning}"
    ));
    assert_that!(installed(&two_levels.project.bin_dir(), "supergraph"))
        .is_equal_to(left.into_iter().map(String::from).collect::<Vec<_>>());
    assert_that!(read(two_levels.project.rover_dir().join("rover.yaml")))
        .is_equal_to(MANIFEST.to_string());
    assert_that!(read(
        two_levels.project.rover_dir().join("plugin-versions.lock")
    ))
    .is_equal_to(LOCKED.to_string());
}

#[rstest]
fn a_floating_alias_is_refused_before_anything_is_removed(two_levels: TwoLevels) {
    declared_project(&two_levels);

    let result = uninstall(&two_levels, &["router", "supergraph@2"]);

    assert_that!(result.code).is_equal_to(Some(1));
    assert_that!(result.stderr.as_str()).is_equal_to(
        "error: `supergraph@2` is ambiguous for uninstall. Name the plugin alone to remove every \
         installed version, or an exact `supergraph@=2.9.3`.\n",
    );
    assert_that!(installed(&two_levels.project.bin_dir(), "router"))
        .is_equal_to(vec!["2.1.0".to_string()]);
}

#[rstest]
fn a_manifest_that_cannot_be_edited_stops_the_uninstall_first(two_levels: TwoLevels) {
    declared_project(&two_levels);
    let flow = "plugins: {router: \"=2.1.0\", supergraph: \"2\"}\n";
    fs::write(two_levels.project.rover_dir().join("rover.yaml"), flow).unwrap();

    let result = uninstall(&two_levels, &["supergraph"]);

    assert_that!(result.code).is_equal_to(Some(1));
    assert_that!(result.stderr.as_str()).is_equal_to(indoc::indoc! {"
        error[E052]: Rover can't update the plugins declared in `[project]/.rover/rover.yaml`.

        Caused by:
            `plugins` is written as a flow mapping (`{ ... }`)
                Write `plugins:` in `[project]/.rover/rover.yaml` as a block mapping of plugin names to versions, or make the change by hand, then re-run the command.
    "});
    assert_that!(installed(&two_levels.project.bin_dir(), "supergraph"))
        .is_equal_to(vec!["2.9.2".to_string(), "2.9.3".to_string()]);
    assert_that!(read(two_levels.project.rover_dir().join("rover.yaml")))
        .is_equal_to(flow.to_string());
    assert_that!(read(
        two_levels.project.rover_dir().join("plugin-versions.lock")
    ))
    .is_equal_to(LOCKED.to_string());
}

#[rstest]
fn a_project_without_its_own_copy_leaves_the_global_one(two_levels: TwoLevels) {
    two_levels.seed_plugin(Level::Global, "supergraph", "2.9.3");

    let result = uninstall(&two_levels, &["supergraph"]);

    assert_that!(result.code).is_equal_to(Some(0));
    assert_that!(result.stderr.as_str()).is_equal_to(
        "`supergraph` isn't installed in this project. It resolves from the global install; \
         re-run with `--global` to remove it there.\n",
    );
    assert_that!(installed(&two_levels.global.bin_dir(), "supergraph"))
        .is_equal_to(vec!["2.9.3".to_string()]);
}

#[rstest]
fn global_leaves_the_projects_copy(two_levels: TwoLevels) {
    two_levels.seed_plugin(Level::Project, "router", "2.1.0");

    let result = uninstall(&two_levels, &["router", "--global"]);

    assert_that!(result.code).is_equal_to(Some(0));
    assert_that!(result.stderr.as_str()).is_equal_to(
        "`router` isn't installed globally. It's installed in this project; re-run without \
         `--global` to remove it there.\n",
    );
    assert_that!(installed(&two_levels.project.bin_dir(), "router"))
        .is_equal_to(vec!["2.1.0".to_string()]);
}

#[rstest]
fn global_removes_the_global_copy(two_levels: TwoLevels) {
    two_levels.seed_plugin(Level::Global, "supergraph", "2.9.3");
    two_levels.seed_plugin(Level::Project, "supergraph", "2.9.3");

    let result = uninstall(&two_levels, &["supergraph", "--global"]);

    assert_that!(result.code).is_equal_to(Some(0));
    assert_that!(result.stderr.as_str())
        .is_equal_to("Removed `supergraph` v2.9.3 from the global install.\n");
    assert_that!(installed(&two_levels.global.bin_dir(), "supergraph")).is_empty();
    assert_that!(installed(&two_levels.project.bin_dir(), "supergraph"))
        .is_equal_to(vec!["2.9.3".to_string()]);
}

#[rstest]
#[case::inside_a_project(
    &[],
    "`supergraph` isn't installed in this project or globally. Nothing was removed.\n"
)]
#[case::globally(
    &["--global"],
    "`supergraph` isn't installed globally. Nothing was removed.\n"
)]
fn uninstalling_what_is_not_there_says_so(
    two_levels: TwoLevels,
    #[case] args: &[&str],
    #[case] expected: &str,
) {
    let result = uninstall(&two_levels, &[&["supergraph"], args].concat());

    assert_that!(result.code).is_equal_to(Some(0));
    assert_that!(result.stderr.as_str()).is_equal_to(expected);
}
